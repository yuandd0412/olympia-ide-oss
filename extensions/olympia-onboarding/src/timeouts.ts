/*---------------------------------------------------------------------------------------------
 *  三处超时集中在这一个文件里，值与原来逐个相同。
 *
 *  为什么不合并成一个常量：三次等待的用户预期完全不同——
 *    - 语法检查是「边写边报」，学生光标还停在那一行，等 20 秒没出结果就再也不会点第二次；
 *    - 环境自检是「点一下就要结论」，探针还要接着跑一遍真实编译+运行，留给编译的只有一分钟；
 *    - 完整编译是「提交前那一次」，学生愿意去倒杯水，两分钟是评测机那边实测的上限。
 *  合并会让这三条预期互相污染；分开成三个命名常量，每条都带着「为什么是这个数」的注释，
 *  下次有人想「统一成 30 秒好了」时，能直接看见他在动哪一条。
 *--------------------------------------------------------------------------------------------*/

/**
 * 语法检查的超时：`-fsyntax-only` 那一趟。比完整编译短，是因为它不出目标文件、不链接，
 * 理论上应该快得多；但如果工具链缺 DLL（cc1plus 加载不起来），再等也是等一个不会来的退出码。
 * 20 秒是「学生愿意盯着面板等」和「卡死探针能尽早报出来」之间的折中。
 */
export const SYNTAX_TIMEOUT_MS = 20000;

/**
 * 完整编译的超时：学生按下 F9 / Shift+F9 后，`execFile` 给 g++ 的上限。
 * 两分钟来自评测机实测——Luogu / NOI 的评测机跑一份 OI 代码通常几秒，但带大模板或
 * 重度 include 的代码会到 30 秒以上，留到 120 秒才不至于把「编得慢」误报成「编不过」。
 * 这条是 `export` 的：`stressTest.ts` 与 `judgeSamples.ts` 都从 `./compile` 读它，
 * 所以这里用 re-export 保留原路径，调用方不用改。
 */
export const COMPILE_TIMEOUT_MS = 120000;

/**
 * 环境自检里「单次编译」这一步的预算：探针要在一轮里跑完 2 个标准 × 2 段源码 = 4 次编译，
 * 外加 4 次运行、子程序加载检查、PATH 注入检查。如果单次也给 120 秒，最坏情况要等 8 分钟
 * 才看到「环境正常」——学生不会等。60 秒是让整轮探针控制在 1–2 分钟内能出结果的那条约束。
 */
export const COMPILE_BUDGET_MS = 60000;
